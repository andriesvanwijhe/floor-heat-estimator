"""Offline identification of water-proxy models; no Home Assistant imports.

Fit open-loop temperature predictions, never estimates generated by the model.
All disk I/O, SciPy imports and optimization belong in an executor worker.
"""

import csv
from dataclasses import dataclass
from datetime import UTC, datetime
import hashlib
import json
import math
from pathlib import Path
from typing import NamedTuple
import time

from .const import FIT_KEYS, SOURCE_KEYS
from .model import Parameters, Sample, advance, finite_number

MAX_WORK_SECONDS = 300
MIN_CYCLES = 5


def source_signature(settings):
    """Partition training files when sources or measurement gates change."""
    keys = (*SOURCE_KEYS, "active_mode", "flow_threshold", "settling_minutes", "maximum_gap_minutes")
    raw = json.dumps({key: settings[key] for key in keys}, sort_keys=True)
    return hashlib.sha256(raw.encode()).hexdigest()[:20]


def configuration_signature(settings):
    """Manual coefficient edits explicitly supersede a previously learned fit."""
    raw = json.dumps({key: settings[key] for key in FIT_KEYS}, sort_keys=True)
    return source_signature(settings) + hashlib.sha256(raw.encode()).hexdigest()[:20]


def read_samples(directory, settings, now, include_legacy=False):
    cutoff = now - settings["learning_days"] * 86400
    folder = Path(directory) / "learning" / source_signature(settings)
    imported = sorted((folder / "imported").glob("????-??-??.csv"))
    files = sorted(folder.glob("????-??-??.csv"))
    if include_legacy:
        files += list(Path(directory).glob("????-??-??.csv"))
    samples = {}
    bad_rows = 0
    for file in imported + sorted(files):
        try:
            day = datetime.fromisoformat(file.stem).date()
            if day < datetime.fromtimestamp(cutoff, UTC).date():
                continue
        except ValueError:
            continue
        with file.open(encoding="utf-8", newline="") as stream:
            for row in csv.DictReader(stream):
                try:
                    stamp = datetime.fromisoformat(row["time_utc"])
                    if stamp.tzinfo is None:
                        raise ValueError("Timestamp must have an offset")
                    timestamp = stamp.timestamp()
                    if not cutoff <= timestamp <= now:
                        continue
                    sample = Sample(timestamp, *(finite_number(row.get(key)) for key in
                        ("room_temperature", "heat_input", "supply_temperature", "return_temperature", "flow")),
                        mode=row.get("mode") or None)
                    # Last file wins, so new signed files override overlapping legacy rows.
                    samples[int(timestamp // 60)] = sample
                except (ValueError, KeyError, TypeError):
                    bad_rows += 1
                if len(samples) > 150000:
                    raise ValueError("Training sample limit exceeded; shorten the learning window")
    return sorted(samples.values(), key=lambda sample: sample.timestamp), bad_rows


@dataclass(frozen=True)
class Point:
    sample: Sample
    observation: float | None
    cycle: int | None


def prepare_points(samples, settings):
    """Recompute validity from raw sensors; never trust recorded estimate flags."""
    result = []
    active_since = None
    previous_time = None
    cycle = 0
    for sample in sorted(samples, key=lambda sample: sample.timestamp):
        if previous_time is not None and sample.timestamp <= previous_time:
            continue
        if previous_time is not None and sample.timestamp - previous_time > settings["maximum_gap_minutes"] * 60:
            active_since = None
        circulating = (sample.mode == settings["active_mode"] and sample.flow is not None
                       and sample.flow > settings["flow_threshold"])
        if not circulating:
            active_since = None
        elif active_since is None:
            active_since = sample.timestamp
            cycle += 1
        observed = (active_since is not None and sample.room is not None
                    and sample.supply is not None and sample.return_temperature is not None
                    and sample.timestamp - active_since >= settings["settling_minutes"] * 60)
        observation = (sample.supply + sample.return_temperature) / 2 if observed else None
        # Implausible data must break the driver segment rather than bridge it.
        if sample.room is not None and not -30 <= sample.room <= 60:
            sample = Sample(sample.timestamp, None, sample.power, sample.supply,
                            sample.return_temperature, sample.flow, sample.mode)
            observation = None
        if observation is not None and not 0 <= observation <= 80:
            observation = None
        result.append(Point(sample, observation, cycle if circulating else None))
        previous_time = sample.timestamp
    return result


def driving_power(sample, settings):
    if sample.room is None or sample.mode in (None, "", "unknown", "unavailable"):
        return None
    return sample.power if sample.mode == settings["active_mode"] else 0.0


class Step(NamedTuple):
    seconds: float
    room: float
    power: float
    target: float | None
    cycle: int | None
    restart: bool


def build_traces(points, settings):
    """Continuous histories, seeded only initially or after a genuine gap.

    Score every valid water observation. Off periods are energy-preserving
    five-minute bins; first settled restart readings are never discarded.
    """
    traces = []
    seed = None
    steps = []
    previous = None
    elapsed = energy = room_integral = 0.0
    seen_cycles = set()
    for point in points:
        sample = point.sample
        power = driving_power(sample, settings)
        broken = (power is None or previous is None or driving_power(previous, settings) is None
                  or sample.timestamp - previous.timestamp > settings["maximum_gap_minutes"] * 60)
        if broken:
            if seed is not None and steps:
                traces.append((seed, steps))
            seed, steps = None, []
            seen_cycles = set()
            elapsed = energy = room_integral = 0.0
        if power is None:
            previous = sample
            continue
        if seed is None:
            if point.observation is not None:
                seed = point.observation
                seen_cycles.add(point.cycle)
            previous = sample
            continue
        seconds = sample.timestamp - previous.timestamp
        elapsed += seconds
        energy += driving_power(previous, settings) * seconds
        room_integral += previous.room * seconds
        if elapsed >= 300 or point.observation is not None:
            restart = point.observation is not None and point.cycle not in seen_cycles
            steps.append(Step(elapsed, room_integral / elapsed, energy / elapsed,
                              point.observation, point.cycle, restart))
            if point.observation is not None:
                seen_cycles.add(point.cycle)
            elapsed = energy = room_integral = 0.0
        previous = sample
    if seed is not None and steps:
        traces.append((seed, steps))
    return traces


def simulate(traces, parameters, check=lambda: None):
    predicted, observed = [], []
    for seed, steps in traces:
        temperature = seed
        for index, step in enumerate(steps):
            seconds, room, power, target = step[:4]
            if index % 32 == 0:
                check()
            temperature = advance(temperature, room, power, seconds, parameters)
            if not math.isfinite(temperature) or not -100 <= temperature <= 200:
                raise ValueError("Divergent temperature trajectory")
            if target is not None:
                predicted.append(temperature)
                observed.append(target)
    return predicted, observed


def fit_samples(samples, settings, now, cancel=None, budget_seconds=MAX_WORK_SECONDS):
    """Return serializable candidates and evidence; this function never applies them."""
    began = time.monotonic()

    def check():
        if cancel is not None and cancel.is_set():
            raise InterruptedError("Fit cancelled")
        if time.monotonic() - began > budget_seconds:
            raise TimeoutError("Fit exceeded the worker time limit")

    cutoff = now - settings["learning_days"] * 86400
    samples = [sample for sample in samples if cutoff <= sample.timestamp <= now]
    points = prepare_points(samples, settings)
    observed = [p for p in points if p.observation is not None and driving_power(p.sample, settings) is not None]
    # Only closed circulation cycles participate in train/validation selection.
    closed = {points[i-1].cycle for i in range(1,len(points))
              if points[i-1].cycle is not None and points[i].cycle != points[i-1].cycle}
    cycles = sorted({point.cycle for point in observed} & closed)
    observed = [point for point in observed if point.cycle in cycles]
    report = {"status": "insufficient_data", "accepted": False, "models": {},
              "sample_count": len(samples), "observation_count": len(observed), "cycle_count": len(cycles),
              "learning_days": settings["learning_days"], "parameters": {}}
    if len(cycles) < MIN_CYCLES or len(observed) < 120:
        report["reason"] = "Need at least five complete circulation cycles and 120 valid temperature observations"
        return report
    if observed[-1].sample.timestamp - observed[0].sample.timestamp < 86400:
        report["reason"] = "Valid observations must span at least 24 hours"
        return report
    validation_cycle = cycles[min(len(cycles)-2, max(3, int(len(cycles)*0.75)))]
    split = min(p.sample.timestamp for p in points if p.cycle == validation_cycle)
    train_points = [p for p in points if p.sample.timestamp < split]
    test_points = [p for p in points if p.sample.timestamp >= split and (p.cycle is None or p.cycle in cycles)]
    train = build_traces(train_points, settings)
    validation = build_traces(test_points, settings)
    train_observations = [step[3] for _, steps in train for step in steps if step[3] is not None]
    test_observations = [step[3] for _, steps in validation for step in steps if step[3] is not None]
    if len(train_observations) < 24 or len(test_observations) < 6:
        report["reason"] = "Need 24 training and six held-out valid water-temperature observations"
        return report
    theta = [p.observation - p.sample.room for p in observed if p.sample.timestamp < split]
    powers = [driving_power(p.sample, settings) for p in train_points
              if driving_power(p.sample, settings) is not None]
    if max(theta) - min(theta) < 1.5 or max(powers) - min(powers) < 0.5:
        report.update(status="poor_excitation", reason="Need varied heat input and at least 1.5 K observed temperature variation")
        return report

    report.update(train_points=len(train_observations),validation_points=len(test_observations),
                  training_cycle_ids=cycles[:cycles.index(validation_cycle)],
                  validation_cycle_ids=cycles[cycles.index(validation_cycle):])
    from .floor_identification import identify
    return identify(train, validation, settings, report, split, check, began)


def fit_recordings(directory, settings, now, cancel=None, include_legacy=False):
    samples, bad_rows = read_samples(directory, settings, now, include_legacy)
    result = fit_samples(samples, settings, now, cancel,
                         budget_seconds=settings.get('floor_fit_max_minutes',5)*60)
    result.update(skipped_rows=bad_rows, included_legacy_recordings=include_legacy)
    return result
